#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Part 4: Supervised classification of magnetotail regions.

This script trains an XGBoost classifier to predict the three region classes
generated by Part 2:

    0 = Not Magnetotail
    1 = South Lobe
    2 = North Lobe

The primary model intentionally preserves the final MSc configuration:
- combined THEMIS-B (THB) and THEMIS-C (THC) data;
- an 80/20 random train/test split with random_state=1;
- Unix time, alpha, K-S distance, clock angle and cone angle as features;
- the final XGBoost hyperparameters selected during the original project.

Two robustness checks are also run:
1. Random split without Unix Time, using the exact same train/test rows.
2. Chronological holdout, training on the earliest ~80% of timestamps and
   testing on the latest ~20%.

The robustness checks are diagnostic only. They do not change the primary
model or its saved outputs.

Outputs
-------
figures/
    part4_confusion_matrix.png
    part4_precision_recall.png
    part4_feature_importance.png

results/part4/
    classification_report.csv
    class_distribution.csv
    primary_test_predictions.csv
    robustness_checks.csv
    model_metadata.json
    environment_versions.json

models/
    xgboost_region_classifier.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import sklearn
import xgboost
from sklearn.metrics import (
    ConfusionMatrixDisplay,
    accuracy_score,
    average_precision_score,
    balanced_accuracy_score,
    classification_report,
    f1_score,
    precision_recall_curve,
    recall_score,
)
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import label_binarize
from xgboost import XGBClassifier


# ---------------------------------------------------------------------------
# Project paths
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[1]

PART_2_DATA_DIR = PROJECT_ROOT / "data" / "part2"
PART_4_DATA_DIR = PROJECT_ROOT / "data" / "part4"
FIGURES_DIR = PROJECT_ROOT / "figures"
RESULTS_DIR = PROJECT_ROOT / "results" / "part4"
MODEL_DIR = PROJECT_ROOT / "models"

THB_LABELS_PATH = PART_2_DATA_DIR / "labelled_thb_all_features.csv"
THC_LABELS_PATH = PART_2_DATA_DIR / "labelled_thc_all_features.csv"

THB_ALPHA_PATH = PART_4_DATA_DIR / "thb_14yr_6hr.txt"
THC_ALPHA_PATH = PART_4_DATA_DIR / "thc_14yr_6hr.txt"


# ---------------------------------------------------------------------------
# Model configuration
# ---------------------------------------------------------------------------

RANDOM_STATE = 1
TEST_SIZE = 0.20
RUN_ROBUSTNESS_CHECKS = True

PRIMARY_FEATURES = [
    "Unix Time",
    "alpha",
    "KS_D",
    "Clock Angle",
    "Cone Angle",
]

PHYSICAL_FEATURES = [
    "alpha",
    "KS_D",
    "Clock Angle",
    "Cone Angle",
]

CLASS_NAMES = {
    0: "Not Magnetotail",
    1: "South Lobe",
    2: "North Lobe",
}

# Part 2 stores:
#   0 = outside magnetotail
#   2 = south lobe
#   3 = north lobe
#
# Part 4 remaps these to consecutive XGBoost classes 0, 1 and 2.
CLUSTER_TO_CLASS = {
    0: 0,
    2: 1,
    3: 2,
}

MODEL_PARAMS = {
    "max_depth": 10,
    "max_leaves": 20,
    "learning_rate": 0.2,
    "n_estimators": 200,
    "random_state": RANDOM_STATE,
}


# ---------------------------------------------------------------------------
# Data loading and preparation
# ---------------------------------------------------------------------------

def require_columns(
    df: pd.DataFrame,
    required_columns: list[str],
    source: Path,
) -> None:
    """Raise a clear error if an input file is missing required columns."""
    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            f"{source.name} is missing required column(s): {missing}. "
            f"Available columns: {list(df.columns)}"
        )


def load_alpha_features(path: Path) -> pd.DataFrame:
    """
    Load six-hour alpha/K-S data and interpolate it onto an hourly grid.

    Duplicate timestamps are averaged before interpolation. Only the three
    columns needed downstream are returned.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"Could not find:\n{path}\n\n"
            "Place the spacecraft alpha/K-S input file in data/part4."
        )

    df = pd.read_csv(path, sep="\t")
    require_columns(df, ["date", "alpha", "KS_D"], path)

    df["date"] = pd.to_datetime(df["date"])

    hourly = (
        df.set_index("date")
        .groupby(level=0)
        .mean(numeric_only=True)
        .resample("h")
        .interpolate(method="linear")
        .reset_index()
    )

    hourly["Unix Time"] = hourly["date"].astype("int64") // 10**9

    return hourly[["Unix Time", "alpha", "KS_D"]].copy()


def load_region_labels(
    path: Path,
    spacecraft: str,
) -> pd.DataFrame:
    """
    Load Part 2 labels and standardise spacecraft-specific angle names.

    Part 1/2 hourly timestamps are approximately one second after the exact
    hour, while the alpha/K-S files are timestamped on the hour. The labels
    are therefore rounded to the nearest hour before the timestamp merge.
    """
    if not path.exists():
        raise FileNotFoundError(f"Could not find:\n{path}")

    spacecraft = spacecraft.lower()
    clock_column = f"{spacecraft} clock angles"
    cone_column = f"{spacecraft} cone angles"

    df = pd.read_csv(path)
    require_columns(
        df,
        [
            "Unix Time",
            clock_column,
            cone_column,
            "2nd Cluster",
        ],
        path,
    )

    df = df[
        [
            "Unix Time",
            clock_column,
            cone_column,
            "2nd Cluster",
        ]
    ].copy()

    label_times = pd.to_datetime(
        pd.to_numeric(df["Unix Time"]),
        unit="s",
    ).dt.round("h")

    df["Unix Time"] = label_times.astype("int64") // 10**9

    df = df.rename(
        columns={
            clock_column: "Clock Angle",
            cone_column: "Cone Angle",
        }
    )

    df["Region Class"] = df["2nd Cluster"].map(CLUSTER_TO_CLASS)

    if df["Region Class"].isna().any():
        unexpected = sorted(
            df.loc[
                df["Region Class"].isna(),
                "2nd Cluster",
            ].unique()
        )
        raise ValueError(
            f"Unexpected Part 2 cluster value(s) in {path.name}: "
            f"{unexpected}. Expected only {sorted(CLUSTER_TO_CLASS)}."
        )

    df["Region Class"] = df["Region Class"].astype(int)
    df["Spacecraft"] = spacecraft.upper()

    return df.drop(columns="2nd Cluster")


def prepare_spacecraft_dataset(
    labels_path: Path,
    alpha_path: Path,
    spacecraft: str,
) -> pd.DataFrame:
    """Merge one spacecraft's Part 2 labels with its alpha/K-S features."""
    labels = load_region_labels(labels_path, spacecraft)
    alpha_features = load_alpha_features(alpha_path)

    combined = labels.merge(
        alpha_features,
        on="Unix Time",
        how="inner",
        validate="one_to_one",
    )

    combined = combined.dropna(
        subset=PRIMARY_FEATURES + ["Region Class"]
    ).reset_index(drop=True)

    matched_fraction = (
        len(combined) / len(labels)
        if len(labels)
        else 0.0
    )

    print(
        f"{spacecraft.upper()}: matched {len(combined):,} of "
        f"{len(labels):,} labelled hourly samples "
        f"({matched_fraction:.1%})."
    )

    return combined


def build_dataset() -> pd.DataFrame:
    """Build the combined THB + THC supervised-learning dataset."""
    thb = prepare_spacecraft_dataset(
        THB_LABELS_PATH,
        THB_ALPHA_PATH,
        spacecraft="thb",
    )
    thc = prepare_spacecraft_dataset(
        THC_LABELS_PATH,
        THC_ALPHA_PATH,
        spacecraft="thc",
    )

    combined = (
        pd.concat([thb, thc], ignore_index=True)
        .sort_values(["Unix Time", "Spacecraft"])
        .reset_index(drop=True)
    )

    if combined.empty:
        raise ValueError(
            "No timestamps matched between the Part 2 labels and the "
            "alpha/K-S data."
        )

    print(f"Combined dataset: {len(combined):,} hourly samples.")
    print("Class distribution:")

    counts = (
        combined["Region Class"]
        .value_counts()
        .sort_index()
    )

    for class_id, count in counts.items():
        print(
            f"  {class_id} ({CLASS_NAMES[class_id]}): "
            f"{count:,}"
        )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    class_distribution = pd.DataFrame(
        {
            "Class ID": counts.index,
            "Class": [
                CLASS_NAMES[class_id]
                for class_id in counts.index
            ],
            "Count": counts.values,
            "Fraction": counts.values / len(combined),
        }
    )
    class_distribution.to_csv(
        RESULTS_DIR / "class_distribution.csv",
        index=False,
    )

    return combined


