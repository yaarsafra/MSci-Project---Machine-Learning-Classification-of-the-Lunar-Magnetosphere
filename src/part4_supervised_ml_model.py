def calculate_metrics(
    y_true: pd.Series,
    y_pred: np.ndarray,
) -> dict[str, float]:
    """Calculate summary metrics suitable for imbalanced multiclass data."""
    labels = list(CLASS_NAMES)

    return {
        "Accuracy": accuracy_score(y_true, y_pred),
        "Balanced Accuracy": balanced_accuracy_score(
            y_true,
            y_pred,
        ),
        "Macro F1": f1_score(
            y_true,
            y_pred,
            average="macro",
        ),
        "Weighted F1": f1_score(
            y_true,
            y_pred,
            average="weighted",
        ),
        "Not MT Recall": recall_score(
            y_true,
            y_pred,
            labels=[0],
            average="macro",
            zero_division=0,
        ),
        "South Lobe Recall": recall_score(
            y_true,
            y_pred,
            labels=[1],
            average="macro",
            zero_division=0,
        ),
        "North Lobe Recall": recall_score(
            y_true,
            y_pred,
            labels=[2],
            average="macro",
            zero_division=0,
        ),
    }


def evaluate_primary_model(
    model: XGBClassifier,
    dataset: pd.DataFrame,
    test_indices: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """
    Evaluate and save the primary random-split model.

    Returns predictions, probabilities and the classification-report table.
    """
    X_test = dataset.loc[test_indices, PRIMARY_FEATURES]
    y_test = dataset.loc[test_indices, "Region Class"]

    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)

    ordered_labels = list(CLASS_NAMES)
    ordered_names = [
        CLASS_NAMES[label]
        for label in ordered_labels
    ]

    print("\nClassification report")
    print("---------------------")
    print(
        classification_report(
            y_test,
            y_pred,
            labels=ordered_labels,
            target_names=ordered_names,
            digits=3,
        )
    )

    primary_metrics = calculate_metrics(y_test, y_pred)

    print(
        f"Overall accuracy: "
        f"{primary_metrics['Accuracy']:.3f}"
    )
    print(
        f"Balanced accuracy: "
        f"{primary_metrics['Balanced Accuracy']:.3f}"
    )
    print(
        f"Macro F1: "
        f"{primary_metrics['Macro F1']:.3f}"
    )

    report_dict = classification_report(
        y_test,
        y_pred,
        labels=ordered_labels,
        target_names=ordered_names,
        output_dict=True,
        zero_division=0,
    )

    report_df = pd.DataFrame(report_dict).T
    report_df.to_csv(
        RESULTS_DIR / "classification_report.csv"
    )

    predictions = dataset.loc[
        test_indices,
        ["Unix Time", "Spacecraft", "Region Class"],
    ].copy()

    predictions["Actual Class"] = predictions[
        "Region Class"
    ].map(CLASS_NAMES)

    predictions["Predicted Class ID"] = y_pred
    predictions["Predicted Class"] = pd.Series(
        y_pred,
        index=predictions.index,
    ).map(CLASS_NAMES)

    probability_lookup = {
        int(class_id): position
        for position, class_id in enumerate(model.classes_)
    }

    for class_id, class_name in CLASS_NAMES.items():
        predictions[f"P({class_name})"] = y_proba[
            :,
            probability_lookup[class_id],
        ]

    predictions = predictions.drop(columns="Region Class")
    predictions = predictions.sort_values(
        ["Unix Time", "Spacecraft"]
    )

    predictions.to_csv(
        RESULTS_DIR / "primary_test_predictions.csv",
        index=False,
    )

    return y_pred, y_proba, report_df


def run_experiment(
    name: str,
    dataset: pd.DataFrame,
    feature_columns: list[str],
    train_indices: np.ndarray,
    test_indices: np.ndarray,
) -> dict[str, float | str | int]:
    """Train and evaluate one robustness experiment."""
    X_train = dataset.loc[train_indices, feature_columns]
    y_train = dataset.loc[train_indices, "Region Class"]

    X_test = dataset.loc[test_indices, feature_columns]
    y_test = dataset.loc[test_indices, "Region Class"]

    model = train_model(X_train, y_train)
    y_pred = model.predict(X_test)

    metrics = calculate_metrics(y_test, y_pred)

    return {
        "Experiment": name,
        "Features": ", ".join(feature_columns),
        "Train Samples": len(train_indices),
        "Test Samples": len(test_indices),
        **metrics,
    }


def run_robustness_checks(
    dataset: pd.DataFrame,
    random_train_indices: np.ndarray,
    random_test_indices: np.ndarray,
    primary_metrics: dict[str, float],
) -> pd.DataFrame:
    """
    Run the two prespecified robustness checks.

    The already-fitted primary model is not trained again. No robustness
    result is used to choose or modify the primary model.
    """
    rows: list[dict[str, float | str | int]] = []

    primary_row = {
        "Experiment": "Primary: random split, all features",
        "Features": ", ".join(PRIMARY_FEATURES),
        "Train Samples": len(random_train_indices),
        "Test Samples": len(random_test_indices),
        **primary_metrics,
    }
    rows.append(primary_row)

    ablation_row = run_experiment(
        name="Ablation: random split, no Unix Time",
        dataset=dataset,
        feature_columns=PHYSICAL_FEATURES,
        train_indices=random_train_indices,
        test_indices=random_test_indices,
    )
    rows.append(ablation_row)

    (
        chronological_train_indices,
        chronological_test_indices,
        cutoff_time,
    ) = make_chronological_split_indices(dataset)

    chronological_row = run_experiment(
        name="Robustness: chronological holdout",
        dataset=dataset,
        feature_columns=PRIMARY_FEATURES,
        train_indices=chronological_train_indices,
        test_indices=chronological_test_indices,
    )

    cutoff_datetime = pd.to_datetime(
        cutoff_time,
        unit="s",
    )
    chronological_row["Split Detail"] = (
        f"Test period starts {cutoff_datetime}"
    )
    rows.append(chronological_row)

    robustness_df = pd.DataFrame(rows)

    majority_baseline = (
        dataset["Region Class"]
        .value_counts(normalize=True)
        .max()
    )

    robustness_df["Majority Baseline Accuracy"] = (
        majority_baseline
    )

    robustness_df.to_csv(
        RESULTS_DIR / "robustness_checks.csv",
        index=False,
    )

    print("\nRobustness checks")
    print("-----------------")

    display_columns = [
        "Experiment",
        "Accuracy",
        "Balanced Accuracy",
        "Macro F1",
        "Not MT Recall",
        "South Lobe Recall",
        "North Lobe Recall",
    ]

    display_df = robustness_df[display_columns].copy()

    for column in display_columns[1:]:
        display_df[column] = display_df[column].map(
            lambda value: f"{value:.3f}"
        )

    print(display_df.to_string(index=False))
    print(
        f"\nMajority-class baseline accuracy: "
        f"{majority_baseline:.3f}"
    )
    print(
        "Robustness checks are diagnostic only and do not "
        "alter the saved primary model."
    )

    return robustness_df


