def plot_confusion_matrix(
    y_test: pd.Series,
    y_pred: np.ndarray,
) -> None:
    """Save a row-normalised confusion matrix for the primary model."""
    class_ids = list(CLASS_NAMES)
    display_names = [
        CLASS_NAMES[class_id]
        for class_id in class_ids
    ]

    fig, ax = plt.subplots(figsize=(7.5, 6.5))

    ConfusionMatrixDisplay.from_predictions(
        y_test,
        y_pred,
        labels=class_ids,
        display_labels=display_names,
        normalize="true",
        values_format=".2f",
        ax=ax,
    )

    ax.set_title("Normalised Confusion Matrix")
    fig.tight_layout()

    fig.savefig(
        FIGURES_DIR / "part4_confusion_matrix.png",
        dpi=300,
        bbox_inches="tight",
    )

    plt.show()
    plt.close(fig)


def plot_precision_recall(
    y_test: pd.Series,
    y_proba: np.ndarray,
    model: XGBClassifier,
) -> None:
    """Save one-vs-rest precision-recall curves for the primary model."""
    class_ids = list(CLASS_NAMES)

    y_test_binarized = label_binarize(
        y_test,
        classes=class_ids,
    )

    probability_column = {
        int(class_id): position
        for position, class_id in enumerate(model.classes_)
    }

    fig, ax = plt.subplots(figsize=(9, 6))

    for output_column, class_id in enumerate(class_ids):
        scores = y_proba[
            :,
            probability_column[class_id],
        ]

        precision, recall, _ = precision_recall_curve(
            y_test_binarized[:, output_column],
            scores,
        )

        average_precision = average_precision_score(
            y_test_binarized[:, output_column],
            scores,
        )

        ax.plot(
            recall,
            precision,
            linewidth=2,
            label=(
                f"{CLASS_NAMES[class_id]} "
                f"(AP = {average_precision:.3f})"
            ),
        )

    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_title("Precision-Recall Curves")
    ax.grid(True)
    ax.legend(loc="lower left")
    fig.tight_layout()

    fig.savefig(
        FIGURES_DIR / "part4_precision_recall.png",
        dpi=300,
        bbox_inches="tight",
    )

    plt.show()
    plt.close(fig)


def plot_feature_importance(
    model: XGBClassifier,
) -> pd.DataFrame:
    """Save XGBoost feature importances for the primary model."""
    importance_df = pd.DataFrame(
        {
            "Feature": PRIMARY_FEATURES,
            "Importance": model.feature_importances_,
        }
    ).sort_values(
        "Importance",
        ascending=True,
    )

    fig, ax = plt.subplots(figsize=(9, 5))

    ax.barh(
        importance_df["Feature"],
        importance_df["Importance"],
    )
    ax.set_xlabel("Feature Importance Score")
    ax.set_title("XGBoost Feature Importance")
    ax.grid(axis="x")
    fig.tight_layout()

    fig.savefig(
        FIGURES_DIR / "part4_feature_importance.png",
        dpi=300,
        bbox_inches="tight",
    )

    plt.show()
    plt.close(fig)

    importance_df.sort_values(
        "Importance",
        ascending=False,
    ).to_csv(
        RESULTS_DIR / "feature_importance.csv",
        index=False,
    )

    return importance_df


