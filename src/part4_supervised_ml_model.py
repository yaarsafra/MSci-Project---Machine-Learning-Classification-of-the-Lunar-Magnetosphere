# Splitting and model fitting
# ---------------------------------------------------------------------------

def make_random_split_indices(
    df: pd.DataFrame,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Reproduce the original 80/20 random split.

    Indices are split instead of X/y directly so the exact same rows can be
    reused for the Unix-Time ablation.
    """
    indices = np.arange(len(df))

    train_indices, test_indices = train_test_split(
        indices,
        test_size=TEST_SIZE,
        random_state=RANDOM_STATE,
    )

    return train_indices, test_indices


def make_chronological_split_indices(
    df: pd.DataFrame,
) -> tuple[np.ndarray, np.ndarray, int]:
    """
    Split by time using the earliest ~80% of unique timestamps for training.

    All samples from the same timestamp remain on the same side of the split.
    """
    unique_times = np.sort(df["Unix Time"].unique())

    cutoff_position = int(
        np.floor((1.0 - TEST_SIZE) * len(unique_times))
    )
    cutoff_position = min(
        max(cutoff_position, 1),
        len(unique_times) - 1,
    )

    cutoff_time = int(unique_times[cutoff_position])

    train_indices = df.index[
        df["Unix Time"] < cutoff_time
    ].to_numpy()

    test_indices = df.index[
        df["Unix Time"] >= cutoff_time
    ].to_numpy()

    if len(train_indices) == 0 or len(test_indices) == 0:
        raise ValueError(
            "Chronological split produced an empty train or test set."
        )

    return train_indices, test_indices, cutoff_time


def train_model(
    X_train: pd.DataFrame,
    y_train: pd.Series,
) -> XGBClassifier:
    """Train the final XGBoost configuration."""
    model = XGBClassifier(**MODEL_PARAMS)
    model.fit(X_train, y_train)
    return model


